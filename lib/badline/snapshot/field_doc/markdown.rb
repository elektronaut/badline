# frozen_string_literal: true

module Badline
  module Snapshot
    module FieldDoc
      # The doc's markdown: one table per module, of each key, its type and
      # its default, with keys that differ only in a unit's number, such as
      # voice1 to voice3, on one row.
      class Markdown
        NAMES = { "c64" => "C64", "vic20" => "VIC-20", "c128" => "C128", "plus4" => "Plus/4", "pet" => "PET",
                  "cbm2" => "CBM-II" }.freeze
        TAG_TYPES = { Keyed::INT => "int", Keyed::BOOL => "bool", Keyed::BYTES => "bytes", Keyed::INTS => "ints",
                      Keyed::TEXT => "text" }.freeze

        # A row: the key, the type, and the defaults each family whose
        # machines read or write it reads it with.
        Row = Struct.new(:key, :type, :defaults)

        INTRO = <<~MARKDOWN
          # Snapshot format

          This file is generated by `rake snapshot:fields` from the code that
          loads a snapshot. Don't edit it by hand. doc/snapshots.md covers
          what a snapshot holds and which versions load.

          A snapshot is a VICE `.vsf` container. The machine is in modules
          named `BL-` plus a unit, each a deflated list of records: a key, a
          type and a value. The types are `int` (a zigzag BER integer), `bool`,
          `bytes`, `ints` (a list of integers) and `text`. A load skips a key
          it doesn't know, and a key that isn't there leaves the value a
          machine built afresh has: the default below. `word`, `byte` and
          `int & 0x..` are ints cut to the latch's width. A text that lists
          its values takes one of them. An optional int is absent when the
          latch holds nothing. A true drive's modules are named from its
          device number, `BL-D8` to `BL-D11`, and the SIDs past the first
          are `BL-SID2` onwards, in the order they were fitted. Keys with
          `<N>` stand for each numbered unit. A default of "written only" is
          a key the load doesn't read, or reads only when the snapshot has
          it. Where the machines differ, the default is given for each, and a
          key only some of them have names them.
        MARKDOWN

        def initialize(loads)
          @modules = {}
          loads.each { |load| add(load) }
        end

        def to_s
          sections = @modules.map do |name, rows|
            families = rows.values.flat_map { |row| row.defaults.keys }.uniq
            ["## #{name}", "", "Written by the #{families.map { |family| NAMES.fetch(family) }.join(', ')}.", "",
             "| Key | Type | Default |", "| --- | --- | --- |",
             *rows.values.map { |row| line(row, families) }].join("\n")
          end
          "#{INTRO}\n#{sections.join("\n\n")}\n"
        end

        private

        def add(load)
          load.fields.each do |name, fields|
            numbered = numbered_keys(load.written[name].keys + fields.map(&:key))
            fields.each { |field| note(name, numbered.fetch(field.key, field.key), field.type, load.family, field) }
            read = fields.to_set(&:key)
            load.written[name].each do |key, tag|
              next if read.include?(key)

              note(name, numbered.fetch(key, key), TAG_TYPES.fetch(tag, "?"), load.family, nil)
            end
          end
        end

        def note(name, key, type, family, field)
          row = (@modules[name] ||= {})[key] ||= Row.new(key, type, {})
          (row.defaults[family] ||= []) << (field ? brief(field.default, field.type) : "written only")
        end

        # Keys that differ only in a number, as the same key with <N>: each
        # key whose number another key in the module shares the rest of.
        def numbered_keys(keys)
          groups = keys.uniq.group_by { |key| key.gsub(/(?<=[a-z])\d+(?=\.|\z)/, "<N>") }
          groups.each_with_object({}) do |(general, members), numbered|
            members.each { |key| numbered[key] = general } if members.length > 1
          end
        end

        def line(row, families)
          each = row.defaults.transform_values { |defaults| summary(defaults.uniq) }
          default = if each.values.uniq.length == 1 && each.length == families.length then each.values.first
                    else each.map { |family, value| "#{NAMES.fetch(family)}: #{value}" }.join("; ")
                    end
          "| `#{row.key}` | #{row.type} | #{default} |"
        end

        def summary(defaults) = defaults.length > 3 ? "varies" : defaults.join(" or ")

        def brief(value, type)
          case value
          when nil then "absent"
          when Array then list(value)
          when String then type.start_with?("bytes") ? list(value.bytes) : value.inspect
          else value.to_s
          end
        end

        def list(values)
          return values.inspect if values.length <= 8

          values.uniq.length == 1 ? "#{values.length} × #{values.first}" : "#{values.length} values"
        end
      end
    end
  end
end
